/**
 * 获取当前语言
 */
let _currentLang = 'zh-CN';

function getCurrentLang() {
  return _currentLang;
}

/**
 * 翻译函数
 * @param {string} key - 翻译键
 * @param {object} params - 模板参数 (e.g. { count: 5 })
 */
function t(key, params) {
  const lang = _currentLang;
  const dict = I18N[lang] || I18N['zh-CN'];
  let text = dict[key] || I18N['zh-CN'][key] || key;
  if (params) {
    Object.keys(params).forEach(k => {
      text = text.replace(`{${k}}`, params[k]);
    });
  }
  return text;
}

/**
 * 应用语言到整个主界面
 * @param {string} lang - 语言代码 'zh-CN' 或 'en-US'
 */
function applyLanguage(lang) {
  _currentLang = lang || 'zh-CN';
  const dict = I18N[_currentLang] || I18N['zh-CN'];

  // 翻译带 data-i18n 属性的元素
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) {
      el.textContent = dict[key];
    }
  });

  // 翻译 placeholder
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (dict[key]) {
      el.setAttribute('placeholder', dict[key]);
    }
  });

  // 翻译 title 属性
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    if (dict[key]) {
      el.setAttribute('title', dict[key]);
    }
  });

  // 更新 html lang 属性
  document.documentElement.setAttribute('lang', _currentLang);

  // 更新页面标题
  document.title = t('app.title');
}

// 把方法直接挂到 I18N 对象上，确保 I18N.t / I18N.applyLanguage / I18N.getCurrentLang 直接可用
I18N.t = t;
I18N.applyLanguage = applyLanguage;
I18N.getCurrentLang = getCurrentLang;

